// Builds the DTCG tokens (tokens/{core,semantic,component}) with Style Dictionary.
//
//   src/styles/generated/tokens.css   CSS custom properties, in @layer po.tokens
//   src/styles/generated/tokens.json  flat list (name, value, type, description, layer) for docs and the manifest
//   dist/tokens/{light,dark}.{js,d.ts} JS/TS objects (only with --dist)
//
// Core and semantic tokens go on :root so every theme selector can override them. Component tokens
// go on `pack-opening` so their references resolve where the component sits, under the closest theme.
import StyleDictionary from 'style-dictionary';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const THEMES = ['light', 'dark'];
const TMP = 'node_modules/.cache/po-tokens';
const OUT = 'src/styles/generated';
const DIST = process.argv.includes('--dist');

const layerOf = (token) =>
  ['core', 'semantic', 'component'].find((layer) => token.filePath.includes(`tokens/${layer}/`));

function config(theme) {
  const css = (layer, selector) => ({
    destination: `${theme}.${layer}.css`,
    format: 'css/variables',
    filter: (token) => layerOf(token) === layer,
    options: { selector, outputReferences: true },
  });
  return {
    source: ['tokens/core/*.tokens.json', `tokens/semantic/${theme}.tokens.json`, 'tokens/component/*.tokens.json'],
    log: { warnings: 'disabled', verbosity: 'default' },
    platforms: {
      css: {
        transformGroup: 'css',
        prefix: 'po',
        buildPath: `${TMP}/`,
        files: [css('core', ':root'), css('semantic', ':root'), css('component', 'pack-opening')],
      },
      meta: {
        transformGroup: 'css',
        prefix: 'po',
        buildPath: `${TMP}/`,
        files: [{ destination: `${theme}.meta.json`, format: 'po/meta' }],
      },
      ...(DIST && {
        js: {
          transformGroup: 'js',
          buildPath: 'dist/tokens/',
          files: [
            { destination: `${theme}.js`, format: 'javascript/esm' },
            { destination: `${theme}.d.ts`, format: 'typescript/es6-declarations' },
          ],
        },
      }),
    },
  };
}

StyleDictionary.registerFormat({
  name: 'po/meta',
  format: ({ dictionary }) =>
    JSON.stringify(
      dictionary.allTokens.map((token) => ({
        name: `--${token.name}`,
        value: token.$value ?? token.value,
        type: token.$type ?? token.type,
        description: token.$description ?? token.comment ?? '',
        layer: layerOf(token),
      })),
      null,
      2,
    ),
});

rmSync(TMP, { recursive: true, force: true });
for (const theme of THEMES) {
  await new StyleDictionary(config(theme)).buildAllPlatforms();
}

// Keeps only the declarations of a generated `selector { … }` block.
const body = (file) => {
  const css = readFileSync(join(TMP, file), 'utf8');
  return css.slice(css.indexOf('{') + 1, css.lastIndexOf('}')).trimEnd();
};
const indent = (text, spaces) => text.replace(/^(?=.)/gm, ' '.repeat(spaces));

const light = body('light.semantic.css');
const dark = body('dark.semantic.css');

const tokensCss = `/* Generated by scripts/build-tokens.mjs from the DTCG tokens in tokens/ (core, semantic, component). Do not edit. */
@layer po.tokens {
  :root {${indent(body('light.core.css'), 2)}
${indent(light, 2)}
  }

  [data-theme='light'] {${indent(light, 2)}
  }

  [data-theme='dark'] {${indent(dark, 2)}
  }

  @media (prefers-color-scheme: dark) {
    :root:not([data-theme='light']) {${indent(dark, 4)}
    }
  }

  pack-opening {${indent(body('light.component.css'), 2)}
  }
}
`;

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'tokens.css'), tokensCss);

const meta = JSON.parse(readFileSync(join(TMP, 'light.meta.json'), 'utf8'));
const darkValues = new Map(JSON.parse(readFileSync(join(TMP, 'dark.meta.json'), 'utf8')).map((t) => [t.name, t.value]));
for (const token of meta) {
  const darkValue = darkValues.get(token.name);
  if (JSON.stringify(darkValue) !== JSON.stringify(token.value)) token.dark = darkValue;
}
writeFileSync(join(OUT, 'tokens.json'), `${JSON.stringify(meta, null, 2)}\n`);

console.log(`Tokens: ${meta.length} (${meta.filter((t) => t.layer === 'component').length} component) → ${OUT}/tokens.css`);
